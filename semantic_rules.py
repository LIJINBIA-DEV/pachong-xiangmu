def target_scope(target: str) -> str:
    if target in ELEMENTS:
        return "element"
    if target in PLACES:
        return "place"
    if target in REFERENCES:
        return "contextual_place"
    # Unknown user keywords must not silently broaden to every nearby object.
    return "specific_target"


